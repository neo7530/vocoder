#!/usr/bin/env python3
"""Emit prototypes for the non-static, column-0, single-line function definitions
of a .cpp file (our porting style), so the header cannot drift from the code."""
import re, sys
args = sys.argv[1:]
prelude = ""
if "--prelude" in args:
    i = args.index("--prelude"); prelude = open(args[i+1]).read(); del args[i:i+2]
src, hdr, guard_ns, includes = args[0], args[1], args[2], args[3:]
sig = re.compile(r"^((?!static|namespace|using|template|//|#)[A-Za-z_][\w:<>,\s\*&\(\)\[\]]*?\)(?:\s*const)?)\s*\{.*$")
protos = []
cont = ""
for line in open(src):
    line = line.rstrip("\n")
    if cont:
        cont += " " + line.strip()
        if "{" in line:
            m = sig.match(cont)
            if m: protos.append(m.group(1).rstrip() + ";")
            cont = ""
        continue
    if re.match(r"^[A-Za-z_]", line) and "(" in line and not line.startswith(("static", "namespace", "using", "template")):
        if "{" in line:
            m = sig.match(line)
            if m: protos.append(m.group(1).rstrip() + ";")
        elif not line.rstrip().endswith(";"):
            cont = line.strip()
body = "\n".join(protos)
out = "// Generated by tools/gen_header.py from %s - do not edit.\n#pragma once\n\n" % src.split("/")[-1]
out += "".join('#include "%s"\n' % i for i in includes) + "\nnamespace %s {\n\n%s\n%s\n\n}  // namespace %s\n" % (guard_ns, prelude, body, guard_ns)
open(hdr, "w").write(out)
print(len(protos), "prototypes ->", hdr)
