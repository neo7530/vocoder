#!/usr/bin/env python3
"""Convert `pub const NAME: [T; N] = [ ... ];` tables from the Rust crate into C++.

Usage: gen_tables.py <rust_file> <out_basename> <namespace>
Writes <out_basename>.h and <out_basename>.cpp. Pure mechanical conversion: a
table's address comment (`/// `0x...` ...`) is carried over, nothing else.
"""
import re, sys

TYPES = {"i16": "int16_t", "u16": "uint16_t", "i32": "int32_t", "u32": "uint32_t",
         "u8": "uint8_t", "usize": "size_t", "i8": "int8_t", "i64": "int64_t", "u64": "uint64_t"}

src = open(sys.argv[1]).read()
base, ns = sys.argv[2], sys.argv[3]
pat = re.compile(r"((?:[ \t]*///[^\n]*\n)*)[ \t]*pub(?:\(crate\))? (?:const|static) ([A-Za-z0-9_]+): \[(\w+); ([^\]]+)\] = \[(.*?)\];", re.S)
decl, defn = [], []
for m in pat.finditer(src):
    doc, name, ty, n, body = m.groups()
    if ty not in TYPES:
        raise SystemExit(f"{name}: unsupported element type {ty}")
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r"(\d)_(\d)", r"\1\2", body)            # 1_000 -> 1000
    body = re.sub(r"(\d)_(\d)", r"\1\2", body)
    body = re.sub(r"\b(0x[0-9a-fA-F_]+)(?:u32|i32|u16|i16)?\b", lambda k: k.group(1).replace("_", ""), body)
    body = re.sub(r"(\d)(?:u32|i32|u16|i16|u8)\b", r"\1", body)
    body = body.strip().rstrip(",")
    n_c = n.strip()
    c = TYPES[ty]
    doc_c = "".join("// " + l.strip()[3:].strip() + "\n" for l in doc.splitlines())
    decl.append(f"{doc_c}extern const {c} {name}[{n_c}];")
    defn.append(f"const {c} {name}[{n_c}] = {{\n{body}\n}};")
SC = re.compile(r"^(?:pub )?const ([A-Z0-9_]+): (usize|i16|u16|i32|u32) = ([^;\n]+);", re.M)
scalars = []
for m in SC.finditer(src):
    name, ty, expr = m.groups()
    expr = re.sub(r"(?<=[0-9a-fA-F])_(?=[0-9a-fA-F])", "", expr)
    mm = re.match(r"^(0x[0-9a-fA-F]+)u16 as i16$", expr.strip())
    if mm: expr = "static_cast<int16_t>(%s)" % mm.group(1)
    ct = {"usize": "size_t", "i16": "int16_t", "u16": "uint16_t", "i32": "int32_t", "u32": "uint32_t"}[ty]
    scalars.append("inline constexpr %s %s = %s;" % (ct, name, expr))
hdr = ("// Generated by tools/gen_tables.py from %s - do not edit.\n#pragma once\n#include <cstddef>\n#include <cstdint>\n\n"
       "namespace %s {\n\n%s\n\n%s\n\n}  // namespace %s\n") % (sys.argv[1].split('/')[-1], ns, "\n".join(scalars), "\n".join(decl), ns)
cpp = ('// Generated by tools/gen_tables.py from %s - do not edit.\n#include "b25/%s.h"\n\nnamespace %s {\n\n%s\n\n}  // namespace %s\n'
       ) % (sys.argv[1].split('/')[-1], base, ns, "\n\n".join(defn), ns)
open(f"include/b25/{base}.h", "w").write(hdr)
open(f"src/{base}.cpp", "w").write(cpp)
print(f"{base}: {len(decl)} tables")
