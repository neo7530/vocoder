#!/usr/bin/env python3
"""Convert the Annex H / S interleave tables and the AMBE+2 bit-priority map from the
Rust `generated/` sources into C++ (pure data conversion)."""
import re, sys
root = sys.argv[1]
def read(n): return open(f"{root}/{n}").read()
def ents(src, name, fields):
    pat = re.compile(name + r"\s*\{([^}]*)\}")
    out = []
    for m in pat.finditer(src):
        vals = dict((k.strip(), int(v)) for k, v in (kv.split(":") for kv in m.group(1).split(",") if kv.strip()))
        out.append("{" + ", ".join(str(vals[f]) for f in fields) + "}")
    return out
H = ents(read("annex_h.rs"), "AnnexHEntry", ["bit1_vec", "bit1_idx", "bit0_vec", "bit0_idx"])
S = ents(read("annex_s.rs"), "AnnexSEntry", ["bit1_vec", "bit1_idx", "bit0_vec", "bit0_idx"])
B = ents(read("ambe_bit_priority.rs"), "BitMap", ["src_param", "src_bit", "dst_vec", "dst_bit"])
assert len(H) == 72 and len(S) == 36 and len(B) == 49, (len(H), len(S), len(B))
def table(name, ty, items):
    return f"const {ty} {name}[{len(items)}] = {{\n  " + ",\n  ".join(items) + ",\n};\n"
hdr = """// Generated by tools/gen_wire_tables.py from the Rust crate's generated/ tables - do not edit.
#pragma once
#include <cstdint>

namespace b25::wire {

struct InterleaveEntry { uint8_t bit1_vec, bit1_idx, bit0_vec, bit0_idx; };
struct BitMap { uint8_t src_param, src_bit, dst_vec, dst_bit; };

extern const InterleaveEntry ANNEX_H[72];  // IMBE (full-rate) dibit interleave
extern const InterleaveEntry ANNEX_S[36];  // AMBE+2 (half-rate) dibit interleave
extern const BitMap AMBE_BIT_MAP[49];      // AMBE+2 bit prioritisation: b-vector bit -> u-vector bit

}  // namespace b25::wire
"""
cpp = '#include "b25/wire_tables.h"\n\nnamespace b25::wire {\n\n' + table("ANNEX_H", "InterleaveEntry", H) + "\n" + table("ANNEX_S", "InterleaveEntry", S) + "\n" + table("AMBE_BIT_MAP", "BitMap", B) + "\n}  // namespace b25::wire\n"
open("include/b25/wire_tables.h", "w").write(hdr)
open("src/wire_tables.cpp", "w").write("// Generated by tools/gen_wire_tables.py - do not edit.\n" + cpp)
print("wire tables:", len(H), len(S), len(B))
